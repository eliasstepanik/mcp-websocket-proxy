import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport, getDefaultEnvironment } from '@modelcontextprotocol/sdk/client/stdio.js';

const require = createRequire(import.meta.url);
const entry = require.resolve('@modelcontextprotocol/server-filesystem/dist/index.js');
const dir = mkdtempSync(join(tmpdir(), 'fsprobe-'));
writeFileSync(join(dir, 'hello.txt'), 'hello fs\n', 'utf8');

const transport = new StdioClientTransport({ command: process.execPath, args: [entry, '--', dir], env: getDefaultEnvironment(), stderr: 'pipe' });
transport.stderr?.on('data', (c) => process.stderr.write('[child] ' + c));
const client = new Client({ name: 'probe', version: '1.0.0' });
client.onerror = (e) => console.log('client onerror:', e.message);
await client.connect(transport);
console.log('info', JSON.stringify(client.getServerVersion()), JSON.stringify(client.getServerCapabilities()));
const tools = await client.listTools();
console.log('tools', tools.tools.length, tools.tools.slice(0,3).map(t=>t.name).join(','));
const listed = await client.callTool({ name: 'list_directory', arguments: { path: dir } });
console.log('list', JSON.stringify(listed));
const read = await client.callTool({ name: 'read_text_file', arguments: { path: join(dir, 'hello.txt') } });
console.log('read', JSON.stringify(read));
const bad = await client.callTool({ name: 'read_text_file', arguments: { path: join(dir, '..', '..', 'etc', 'passwd') } });
console.log('outside', JSON.stringify(bad).slice(0, 300));
const bad2 = await client.callTool({ name: 'read_text_file', arguments: { path: '../../../etc/passwd' } });
console.log('outside2', JSON.stringify(bad2).slice(0, 300));
console.log('resources', JSON.stringify(await client.listResources()).slice(0,200));
await client.close();
rmSync(dir, { recursive: true, force: true });
